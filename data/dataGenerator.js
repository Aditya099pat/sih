    const timestamp = `${day} ${['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'][month - 1]} ${year}, ${timeStr}`;

    const dataPayload = {
      blockId: `BLK-${idx.toString().padStart(5, '0')}`,
      instrumentRef: inst.ref,
      instituteCode: inst.instituteCode,
      institution: inst.instituteName,
      principal: inst.principalAmount,
      bank: inst.bankName,
      sfmsRef: inst.sfmsReference,
      status: inst.statutoryStatus
    };

    const blockHash = simpleHash(blockIndex + timestamp + prevHash + JSON.stringify(dataPayload) + action);

