// Helper to generate deterministic SHA-256-like hex string
export function simpleHash(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash |= 0;
  }
  const hex1 = Math.abs(hash).toString(16).padStart(8, "0");
  const hex2 = Math.abs(hash * 31 + 17).toString(16).padStart(8, "0");
  const hex3 = Math.abs(hash * 13 + 47).toString(16).padStart(8, "0");
  const hex4 = Math.abs(hash * 7 + 89).toString(16).padStart(8, "0");
  const hex5 = Math.abs(hash * 53 + 101).toString(16).padStart(8, "0");
  const hex6 = Math.abs(hash * 97 + 13).toString(16).padStart(8, "0");
  const hex7 = Math.abs(hash * 19 + 71).toString(16).padStart(8, "0");
  const hex8 = Math.abs(hash * 29 + 43).toString(16).padStart(8, "0");
  return (hex1 + hex2 + hex3 + hex4 + hex5 + hex6 + hex7 + hex8).substring(0, 64);
}

